const darkPalettes = new Set([4, 5, 6, 7, 9, 15, 16, 17, 18, 21, 22, 26]);

// Interleave the families before arranging them into the desktop grid.
const studies: CardRecipe[] = Array.from({ length: 10 }, (_, designIndex) =>
  collections.map(({ family, designs }, familyIndex) => {
    const [
      name,
      paletteIndex,
      columns,
      rows,
      motif,
      composition,
      title,
      body,
      detail,
      image,
    ] = designs[designIndex];
    const seed = designIndex * 10 + familyIndex;
    return {
      id: String(seed + 1).padStart(3, "0"),
      name,
      family,
      palette: palettes[paletteIndex],
      columns,
      rows,
      motif,
      composition,
      title,
      body,
      detail,
      image,
      dark: darkPalettes.has(paletteIndex),
      motion: designIndex === familyIndex,
      seed,
    };
  })
).flat();

function fits(
  card: CardRecipe,
  row: number,
  column: number,
  occupied: boolean[][]
): boolean {
  if (column + card.columns > 4) {
    return false;
  }
  for (let y = row; y < row + card.rows; y += 1) {
    for (let x = column; x < column + card.columns; x += 1) {
      if (occupied[y]?.[x]) {
        return false;
      }
    }
  }
  return true;
}

function arrangeGallery(source: CardRecipe[]): CardRecipe[] {
  const remaining = [...source];
  const arranged: CardRecipe[] = [];
  const occupied: boolean[][] = [];
  let row = 0;
  let column = 0;
  while (remaining.length > 0) {
    if (column === 4) {
      row += 1;
      column = 0;
    }
    if (occupied[row]?.[column]) {
      column += 1;
      continue;
    }
    const startRow = row;
    const startColumn = column;
    const candidate = remaining.findIndex((card) =>
      fits(card, startRow, startColumn, occupied)
    );
    if (candidate === -1) {
      column += 1;
      continue;
    }
    const [card] = remaining.splice(candidate, 1);
    for (let y = row; y < row + card.rows; y += 1) {
      occupied[y] ??= [];
      for (let x = column; x < column + card.columns; x += 1) {
        occupied[y][x] = true;
      }
    }
    arranged.push({
      ...card,
      id: String(arranged.length + 1).padStart(3, "0"),
    });
    column += card.columns;
  }
  return arranged;
}

// Pack in source order rather than using CSS dense placement, so focus and
// screen-reader order follow the visual sequence. IDs follow that same order.
export const cards: readonly CardRecipe[] = arrangeGallery(studies);
