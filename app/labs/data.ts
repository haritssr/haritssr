/** Latest known update, regardless of history order; falls back to creation. */
export function getLatestLabUpdate(lab: LabEntry): string {
  let latest = lab.createdAt;
  for (const date of lab.updatedAt) {
    if (date > latest) {
      latest = date;
    }
  }
  return latest;
}

export function getLabDomain(slug: string): LabDomain {
  const domain = LabsData.find((entry) => entry.slug === slug);

  if (!domain) {
    throw new Error(`Unknown lab domain: ${slug}`);
  }

  return domain;
}

function getLab(domainSlug: string, labSlug: string): LabEntry {
  const domain = getLabDomain(domainSlug);
  const lab = domain.labs.find((entry) => entry.slug === labSlug);

  if (!lab) {
    throw new Error(`Unknown lab: ${domainSlug}/${labSlug}`);
  }

  return lab;
}

export function getLabDomainMetadata(slug: string): Metadata {
  const domain = getLabDomain(slug);
  return createPageMetadata({
    title: `${domain.title} Labs`,
    description: domain.description,
    path: `/labs/${domain.slug}`,
  });
}

export function getLabMetadata(
  domainSlug: string,
  labSlug: string,
  overrides: { description?: string } = {}
): ReturnType<typeof createPageMetadata> {
  const domain = getLabDomain(domainSlug);
  const lab = getLab(domainSlug, labSlug);
  return createPageMetadata({
    title: `${lab.title} | ${domain.title} Labs`,
    description: overrides.description ?? lab.description,
    path: `/labs/${domainSlug}/${labSlug}`,
  });
}
